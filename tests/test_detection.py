from pathlib import Path

import cv2
import numpy as np
import pytest

from sudokuscan.config import ScanConfig
from sudokuscan.corners import detect_outer_corners
from sudokuscan.geometry import order_points
from sudokuscan.preprocessing import preprocess_image


def test_synthetic_perspective_detection_uses_harris_candidates():
    root = Path(__file__).resolve().parents[1]
    image = cv2.imread(str(root / "examples" / "synthetic" / "synthetic_01.png"))
    assert image is not None
    _gray, normalized, binary = preprocess_image(image)
    detection = detect_outer_corners(normalized, binary, ScanConfig())
    assert detection is not None
    assert len(detection.candidates) >= 100
    assert detection.corners.shape == (4, 2)

    # cornerSubPix can move a Harris maximum slightly; the final corner must
    # remain close to a point generated by the Harris response map.
    for corner in detection.corners:
        distances = np.linalg.norm(detection.candidates - corner[None, :], axis=1)
        assert float(np.min(distances)) < 3.0

    truth = np.array([[155, 92], [670, 122], [635, 615], [112, 574]], dtype=np.float32)
    predicted = order_points(detection.corners)
    mean_side = np.mean([np.linalg.norm(truth[1] - truth[0]),
                         np.linalg.norm(truth[2] - truth[1]),
                         np.linalg.norm(truth[3] - truth[2]),
                         np.linalg.norm(truth[0] - truth[3])])
    error_percent = np.mean(np.linalg.norm(predicted - truth, axis=1)) / mean_side * 100
    assert error_percent < 2.0


def test_wide_subpixel_refinement_recovers_weak_corner_under_strong_keystone():
    """Regression for an outer Harris maximum displaced along the top border."""
    from sudokuscan.corners import _refine

    # Rebuild the strong-perspective synthetic target that previously selected
    # (679, 307) instead of the actual top-right intersection (700, 320).
    puzzle = np.full((450, 450, 3), 255, np.uint8)
    values = np.array([
        [5, 3, 0, 0, 7, 0, 0, 0, 0],
        [6, 0, 0, 1, 9, 5, 0, 0, 0],
        [0, 9, 8, 0, 0, 0, 0, 6, 0],
        [8, 0, 0, 0, 6, 0, 0, 0, 3],
        [4, 0, 0, 8, 0, 3, 0, 0, 1],
        [7, 0, 0, 0, 2, 0, 0, 0, 6],
        [0, 6, 0, 0, 0, 0, 2, 8, 0],
        [0, 0, 0, 4, 1, 9, 0, 0, 5],
        [0, 0, 0, 0, 8, 0, 0, 7, 9],
    ], dtype=np.int32)
    for i in range(10):
        coordinate = min(449, i * 50)
        thickness = 3 if i % 3 == 0 else 1
        cv2.line(puzzle, (coordinate, 0), (coordinate, 449), 0, thickness, cv2.LINE_AA)
        cv2.line(puzzle, (0, coordinate), (449, coordinate), 0, thickness, cv2.LINE_AA)
    for row in range(9):
        for col in range(9):
            value = int(values[row, col])
            if value:
                cv2.putText(puzzle, str(value), (col * 50 + 17, row * 50 + 37),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.72, 0, 2, cv2.LINE_AA)

    destination = np.array([[470, 130], [700, 320], [620, 830], [100, 620]], np.float32)
    source = np.array([[0, 0], [450, 0], [450, 450], [0, 450]], np.float32)
    transform = cv2.getPerspectiveTransform(source, destination)
    warped = cv2.warpPerspective(puzzle, transform, (1000, 1000),
                                 borderValue=(235, 235, 235))
    mask = cv2.warpPerspective(np.full((450, 450), 255, np.uint8), transform,
                               (1000, 1000))
    image = np.full((1000, 1000, 3), 235, np.uint8)
    image[mask > 0] = warped[mask > 0]
    gray, _normalized, _binary = preprocess_image(image)

    initial_harris = np.array([
        [471, 135], [679, 307], [619, 828], [102, 619]
    ], dtype=np.float32)
    refined = _refine(gray, initial_harris, destination)
    before_error = float(np.linalg.norm(initial_harris[1] - destination[1]))
    after_error = float(np.linalg.norm(refined[1] - destination[1]))
    assert before_error > 20.0
    assert after_error < 10.0


def test_strong_keystone_harris_detection_aligns_grid_after_homography():
    """Regression: steep perspective must not pull outer corners to inner nodes."""
    root = Path(__file__).resolve().parents[1]
    source_image = cv2.imread(str(root / "examples" / "synthetic" / "synthetic_01.png"))
    annotation = __import__("json").loads(
        (root / "examples" / "synthetic" / "synthetic_01.json").read_text()
    )
    assert source_image is not None
    source_corners = np.asarray(annotation["corners"], dtype=np.float32)
    square = np.asarray([[0, 0], [450, 0], [450, 450], [0, 450]], dtype=np.float32)
    source_to_square = cv2.getPerspectiveTransform(source_corners, square)
    board = cv2.warpPerspective(source_image, source_to_square, (450, 450))

    # Reproject the known square into a strongly foreshortened quadrilateral.
    truth = np.asarray([[400, 100], [620, 145], [820, 877], [100, 817]], dtype=np.float32)
    square_to_photo = cv2.getPerspectiveTransform(square, truth)
    warped = cv2.warpPerspective(board, square_to_photo, (1000, 1000),
                                 borderValue=(235, 235, 235))
    mask = cv2.warpPerspective(np.full((450, 450), 255, np.uint8),
                               square_to_photo, (1000, 1000))
    photograph = np.full((1000, 1000, 3), 235, dtype=np.uint8)
    photograph[mask > 0] = warped[mask > 0]

    _gray, normalized, binary = preprocess_image(photograph)
    detection = detect_outer_corners(normalized, binary, ScanConfig())
    assert detection is not None
    predicted = order_points(detection.corners)
    side = np.mean([np.linalg.norm(truth[(i + 1) % 4] - truth[i]) for i in range(4)])
    corner_error_percent = (
        np.mean(np.linalg.norm(predicted - truth, axis=1)) / side * 100.0
    )
    assert corner_error_percent < 1.0

    # The final points must still be drawn from the multiscale Harris candidate
    # set (with only local subpixel refinement), not copied from the region proposal.
    nearest = np.linalg.norm(
        predicted[:, None, :] - detection.candidates[None, :, :], axis=2
    ).min(axis=1)
    assert float(nearest.max()) < 3.0

    homography = cv2.getPerspectiveTransform(predicted.astype(np.float32), square)
    rectified = cv2.warpPerspective(photograph, homography, (450, 450))
    from sudokuscan.geometry import grid_line_deviations
    metrics = grid_line_deviations(rectified)
    assert metrics["rms_px"] < 1.5
    assert metrics["spacing_rms_px"] < 1.5


@pytest.mark.parametrize("returned_shape", [(4, 1, 4), (4, 4), (1, 4, 4)])
def test_hough_proposals_accept_opencv_line_array_shapes(monkeypatch, returned_shape):
    """OpenCV 4/5 builds expose HoughLinesP as different 4-coordinate layouts."""
    from sudokuscan.corners import _hough_grid_quads

    # Four long lines in two perpendicular families are enough to enter the
    # proposal pipeline; the actual returned quadrilateral is not used as a
    # final corner source (Harris matching is tested elsewhere).
    raw_segments = np.asarray([
        [100, 100, 800, 100],
        [100, 800, 800, 800],
        [100, 100, 100, 800],
        [800, 100, 800, 800],
    ], dtype=np.int32)
    shaped = raw_segments.reshape(returned_shape)
    monkeypatch.setattr(cv2, "HoughLinesP", lambda *args, **kwargs: shaped.copy())
    gray = np.full((1000, 1000), 230, dtype=np.uint8)
    proposals = _hough_grid_quads(gray, ScanConfig())
    assert len(proposals) == 1
    assert proposals[0].shape == (4, 2)


def test_full_detection_accepts_flattened_hough_lines(monkeypatch):
    """Regression for OpenCV builds returning Hough lines as (N, 4)."""
    root = Path(__file__).resolve().parents[1]
    image = cv2.imread(str(root / "examples" / "synthetic" / "synthetic_01.png"))
    assert image is not None
    original_hough = cv2.HoughLinesP

    def flattened_hough(*args, **kwargs):
        lines = original_hough(*args, **kwargs)
        return None if lines is None else np.asarray(lines).reshape(-1, 4)

    monkeypatch.setattr(cv2, "HoughLinesP", flattened_hough)
    _gray, normalized, binary = preprocess_image(image)
    detection = detect_outer_corners(normalized, binary, ScanConfig())
    assert detection is not None
    assert detection.corners.shape == (4, 2)
